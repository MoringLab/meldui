import { mkdir, readFile, writeFile } from "node:fs/promises";
import { classifyRow, FAILURE_CLASSES } from "./lib/taxonomy.js";

const input = process.argv[2] ?? "docs/verification/online-final.json";
const output = process.argv[3] ?? "docs/quality/failure-taxonomy.md";
const { results } = JSON.parse(await readFile(input, "utf8")) as { results: any[] };
const routes = [...new Set(results.map((r) => r.model))];
const lines = [
  "# Failure taxonomy",
  "",
  `Source: \`${input}\` (${results.length} jobs). Generated by \`pnpm tsx scripts/taxonomy.ts\`; every job stays in the denominator.`,
  "Classes are assigned from diagnostic codes (the dominant class per job; any infra code makes the job `infra` because quality was not measurable).",
  "",
];
for (const route of routes) {
  const rows = results.filter((r) => r.model === route);
  const first = rows.filter((r) => !r.initialValid);
  lines.push(
    `## ${route}`,
    "",
    `${rows.length} jobs · first pass ${rows.length - first.length}/${rows.length} · final ${rows.filter((r) => r.valid).length}/${rows.length}`,
    "",
    "| Class | First-pass failures | Still failing after repair | Examples |",
    "|---|---:|---:|---|",
  );
  for (const cls of FAILURE_CLASSES) {
    const f = first.filter((r) => classifyRow(r) === cls);
    const final = rows.filter((r) => !r.valid && classifyRow(r) === cls);
    lines.push(
      `| ${cls} | ${f.length} | ${final.length} | ${[...new Set(f.map((r) => r.id))].slice(0, 3).join(", ") || "–"} |`,
    );
  }
  const codes = new Map<string, number>();
  for (const r of results.filter((x) => x.model === route))
    for (const c of r.errors ?? []) codes.set(c, (codes.get(c) ?? 0) + 1);
  lines.push(
    "",
    `Raw diagnostic codes: ${[...codes.entries()].sort((a, b) => b[1] - a[1]).map(([c, n]) => `\`${c}\`×${n}`).join(", ") || "none"}`,
    "",
  );
}
lines.push(
  "## Top causes of first-pass failure (hypotheses, to be tested in M6)",
  "",
  "| # | Cause | Evidence | Hypothesis | Proposed fix |",
  "|---|---|---|---|---|",
  "| 1 | Route availability (`GATEWAY_HTTP_429`, stream errors) | Claude 36/36, Gemini 4 jobs | Quota, not model quality | Route health + bounded backoff (M0); report as unavailable, never as 0/30 quality |",
  "| 2 | Malformed JSON lines (`INVALID_JSON`) | Gemini ×91 raw diagnostics, GPT ×9 | Pretty-printed or fenced envelopes; multi-line objects | Tolerant line reassembly (logged normalization), prompt line-per-envelope example, structured output where supported |",
  "| 3 | Invalid component props (`INVALID_COMPONENT`) | Gemini ×54, GPT ×5 | Nested `props`, wrong enums, missing required props | Compact schema in prompt, per-component required-prop table, repair report with path/expected/got |",
  "| 4 | Envelope shape (`INVALID_SCHEMA`, `MISSING_ROOT`) | Gemini ×10, GPT ×4 | Root id omitted or sent last; extra keys on envelopes | Emission-order rules (root first), strict-envelope reminder |",
  "| 5 | Expression type errors (`EXPECTED_*`) | Gemini ×6 | Scalar operands for aggregate ops; string/number mixing | Op signature table in prompt; deterministic coercion behind a flag |",
  "",
  "Semantic failures (wrong numbers, dead interactions, bad layout) are not visible in this source; they are measured by the M1 behavioral, numeric and layout layers.",
);
await mkdir("docs/quality", { recursive: true });
await writeFile(output, `${lines.join("\n")}\n`);
console.log(lines.join("\n"));
